"""Simulated factory personas for the demo (PLAN_V2 §5, decision 26 Nov 2026).

The persona messages are HAND-WRITTEN by the Bunon team (not generated by an LLM) and frozen in
data/demo/personas.json, so the live demo replays fixed text and cannot fail. Every persona and every
message is labelled "simulated" in the app. The LLM only *parses* these messages, like any reply.

How to fill the file: data/demo/PERSONAS_GUIDE.md. Check it with:
    python -m bunon.personas
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from bunon import config as C
from bunon import textnum as tn

PIECE_PERSONAS_PATH = C.ROOT / "data" / "demo" / "personas.json"  # the pre-D30 piece-split demo (regression tests)
PERSONAS_PATH = C.ROOT / "data" / "demo" / "personas_programme.json" if C.DEMO_PROGRAMME else PIECE_PERSONAS_PATH
FORMAT_VERSION = 1

Language = Literal["English", "Banglish", "Bangla"]
MessageKind = Literal["offer_reply", "progress_update", "rescue_reply", "delivery_note", "other"]
Profile = Literal["reliable", "over_promises", "counters_on_price", "declines", "slow_to_answer", "other"]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Expected(_Strict):
    """What the writer MEANT the message to say. Used as the answer key for the parser tests.
    Every number here must be written in the message text itself (checked by validate())."""
    decision: Literal["accept", "reject", "counter"] | None = None   # offer_reply / rescue_reply
    qty: int | None = Field(None, ge=0)                 # pieces offered or confirmed
    price_bdt_per_piece: float | None = Field(None, ge=0)
    ship_date: date | None = None                       # a calendar date stated in the message
    pieces_done: int | None = Field(None, ge=0)         # progress_update: cumulative pieces finished
    delay_days: int | None = Field(None, ge=0)          # progress_update / offer: days late
    workers_present: int | None = Field(None, ge=0)     # progress_update: workers who came (D31)
    workers_planned: int | None = Field(None, ge=0)     # progress_update: workers planned (D31)
    cause: str | None = None                            # free words: "power cut", "fabric late", ...
    note: str | None = None                             # anything else the parser should notice


class PersonaMessage(_Strict):
    msg_id: str = Field(pattern=r"^[a-z0-9_]+$")
    story_day: int = Field(ge=0, le=60)                 # day of the demo order (day 0 = order received)
    kind: MessageKind
    text: str = Field(min_length=1)
    expected: Expected = Expected()
    placeholder: bool = False                           # True = developer's stand-in text, to be replaced by the team


class Persona(_Strict):
    persona_id: str = Field(pattern=r"^[a-z0-9_]+$")
    factory_id: str = Field(pattern=r"^(F\d{4}|TBD)$")  # pseudonymous ID; "TBD" until the fixture is built
    label: str                                          # short description shown in the app
    language: Language
    profile: Profile
    style_notes: str = ""                               # how this persona writes (for the team, not the app)
    example: bool = False                               # True = format example, never used in the demo
    messages: list[PersonaMessage]


class QCScript(_Strict):
    """Scripted outcome at the exporter's QC, as SHARES (the code turns them into pieces from the approved
    allocation). Simulated; the quality inspector sees it as a pre-filled form and can change it."""
    factory_id: str = Field(pattern=r"^F\d{4}$")
    story_day: int = Field(ge=0, le=60)
    delivered_share: float = Field(ge=0, le=1)          # share of the allocated pieces that arrive
    reject_share: float = Field(ge=0, le=1)             # share of delivered pieces rejected at QC
    lot_rejected: bool = False
    placeholder: bool = False


class PersonaFile(_Strict):
    format_version: int
    simulated_notice: str
    personas: list[Persona]
    qc_script: list[QCScript] = []

    @model_validator(mode="after")
    def _unique(self) -> "PersonaFile":
        pids = [p.persona_id for p in self.personas]
        if len(pids) != len(set(pids)):
            raise ValueError("persona_id values must be unique")
        mids = [m.msg_id for p in self.personas for m in p.messages]
        if len(mids) != len(set(mids)):
            raise ValueError("msg_id values must be unique across all personas")
        fids = [p.factory_id for p in self.personas if p.factory_id != "TBD"]
        if len(fids) != len(set(fids)):
            raise ValueError("each factory_id may belong to only one persona")
        return self


def validate(pf: PersonaFile) -> list[str]:
    """Problems that do not break loading but make a message unusable as a parser test.
    Each number in `expected` must be literally stated in the message (digits, 9 hajar, ১২, ...)."""
    out = []
    if pf.format_version != FORMAT_VERSION:
        out.append(f"format_version is {pf.format_version}, expected {FORMAT_VERSION}")
    for p in pf.personas:
        for m in p.messages:
            e = m.expected
            for name in ("qty", "price_bdt_per_piece", "pieces_done", "delay_days", "workers_present",
                         "workers_planned"):
                v = getattr(e, name)
                if v is not None and not tn.states_number(m.text, float(v)):
                    out.append(f"{m.msg_id}: expected.{name} = {v} is not written in the text "
                               "(write it as digits, or tell the developer which word form you used)")
            if e.ship_date is not None and not tn.states_date(m.text, e.ship_date):
                out.append(f"{m.msg_id}: expected.ship_date {e.ship_date} is not written in the text as a date")
            if m.kind in ("offer_reply", "rescue_reply") and e.decision is None:
                out.append(f"{m.msg_id}: an {m.kind} needs expected.decision (accept / reject / counter)")
    return out


def messages_for(pf: PersonaFile, factory_id: str, kind: str) -> list[PersonaMessage]:
    return [m for p in pf.personas if p.factory_id == factory_id for m in p.messages if m.kind == kind]


def load(path: Path = PERSONAS_PATH, include_examples: bool = False) -> PersonaFile:
    pf = PersonaFile.model_validate(json.loads(path.read_text(encoding="utf-8")))
    if not include_examples:
        pf = pf.model_copy(update={"personas": [p for p in pf.personas if not p.example]})
    return pf


def main(path: str | None = None) -> int:
    pf = load(Path(path) if path else PERSONAS_PATH, include_examples=True)
    n_msgs = sum(len(p.messages) for p in pf.personas)
    print(f"{len(pf.personas)} personas ({sum(p.example for p in pf.personas)} examples), {n_msgs} messages")
    problems = validate(pf)
    for line in problems:
        print("  -", line)
    print("OK" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:2]))
