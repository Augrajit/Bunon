"""Human-in-the-loop record: every approval or rejection is logged; nothing is ever sent.

The log lives in data/runtime/decisions.db (gitignored). On Streamlit Cloud that disk is
ephemeral, which is fine for a demo: the log shows what this server instance has recorded.
Approvers are recorded by role, not by name, so the demo collects no personal data.
"""
from __future__ import annotations

import json
import os
import sqlite3
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Literal

import pandas as pd

from bunon import config as C
from bunon.schemas import AllocationPlan, Candidate, OrderConstraints

LOG_DB = C.ROOT / "data" / "runtime" / "decisions.db"
LOG_DB_ENV = "BUNON_DECISIONS_DB"  # tests point the log elsewhere so they never touch the real one
from bunon.store import ROLES  # exporter roles, then factory roles (PLAN_V2 §4)  # noqa: E402


def _log_path(path: Path | None) -> Path:
    return path or Path(os.environ.get(LOG_DB_ENV) or LOG_DB)


def _con(path: Path | None) -> sqlite3.Connection:
    path = _log_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path)
    con.execute("""CREATE TABLE IF NOT EXISTS decisions (
        ts_utc TEXT NOT NULL, step TEXT NOT NULL, decision TEXT NOT NULL, role TEXT NOT NULL,
        plan_id TEXT, summary TEXT, payload TEXT)""")
    return con


def log_decision(step: str, decision: Literal["approved", "rejected", "confirmed"], role: str,
                 plan_id: str | None = None, summary: str = "", payload: dict | None = None,
                 path: Path | None = None) -> None:
    if role not in ROLES:
        raise ValueError(f"unknown role {role!r}")
    with _con(path) as con:
        con.execute("INSERT INTO decisions VALUES (?,?,?,?,?,?,?)", (
            datetime.now(timezone.utc).isoformat(timespec="seconds"), step, decision, role, plan_id, summary,
            json.dumps(payload or {}, default=str)))


def read_log(path: Path | None = None, limit: int = 50) -> pd.DataFrame:
    with _con(path) as con:
        return pd.read_sql("SELECT ts_utc, step, decision, role, plan_id, summary FROM decisions "
                           "ORDER BY ts_utc DESC LIMIT ?", con, params=(limit,))


def draft_po_text(order: OrderConstraints, plan: AllocationPlan, cands: list[Candidate],
                  approved_by_role: str) -> str:
    """Deterministic draft purchase-order requests, one per factory. Never sent by the system."""
    by_id = {c.factory_id: c for c in cands}
    head = [
        "DRAFT - NOT SENT. Generated by the Bunon prototype for human review.",
        "Factories are shown by pseudonymous ID; all capacity and performance figures are synthetic.",
        f"Plan {plan.plan_id}, approved in the prototype by: {approved_by_role}.",
        "",
    ]
    body = []
    for ln in plan.lines:
        c = by_id[ln.factory_id]
        finish = order.deadline.toordinal() - C.QC_DAYS - c.transit_days - c.slack_days
        body += [
            f"--- Subcontract request to {ln.factory_id} ({c.district}) ---",
            f"Product: basic crew-neck T-shirt; fabric: {order.fabric or 'as per tech pack'}"
            + (f", {order.gsm} GSM" if order.gsm else ""),
            f"Quantity: {ln.qty:,} pieces",
            f"CM price: {ln.unit_price_bdt:.2f} BDT per piece (synthetic placeholder)",
            f"Production complete by: {date.fromordinal(finish):%d %b %Y} "
            f"(buyer deadline {order.deadline:%d %b %Y} is fixed)",
            f"Quality: AQL {order.quality_aql}" if order.quality_aql else "Quality: as per buyer standard",
            "Compliance: unit must remain RSC-covered or hold a valid amfori BSCI audit.",
            "",
        ]
    return "\n".join(head + body)
